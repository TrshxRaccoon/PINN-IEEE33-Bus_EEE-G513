#!/usr/bin/env python3
"""
plot_results.py -- Publication-Quality Benchmark Plotting Suite for TCN State Estimation
========================================================================================
Reads benchmark CSV files (`benchmark_clean.csv` and `benchmark_augmented.csv`)
generated by `train_tcn.py` from the expanded lambda sweep:
  λ ∈ [0.0, 10⁻⁴, 10⁻³, 10⁻², 10⁻¹, 10⁰, 10¹, 10², 10³]

Generates high-resolution (300 DPI) publication-ready comparison figures:
  1. Voltage Magnitude RMSE (|V|) vs PMU Coverage (%)
  2. Voltage Phase Angle RMSE (θ) vs PMU Coverage (%)

Key Design Features:
  - Cleanly accommodates the expanded 9-point lambda sweep up to 10³.
  - Conspicuously highlights the unconstrained Baseline (λ=0) vs. the best
    Physics-Informed TCN (PI-TCN) regularized model.
  - Applies perceptually uniform, scientific color palettes with distinctive markers.
  - Automatically exports figures to the specified output directory (default: `plots/`).
"""

import argparse
import math
import os
import sys
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
from matplotlib.colors import Normalize
import matplotlib.cm as cm


def format_lambda_label(lam: float, is_best: bool = False) -> str:
    """Format lambda value into publication-grade scientific or decimal label."""
    if lam == 0.0:
        return "Baseline (λ=0)"
    
    # Power of 10 representation
    log_val = math.log10(lam)
    if abs(log_val - round(log_val)) < 1e-5:
        exp = int(round(log_val))
        superscripts = {
            "-4": "⁻⁴", "-3": "⁻³", "-2": "⁻²", "-1": "⁻¹",
            "0": "⁰", "1": "¹", "2": "²", "3": "³"
        }
        exp_str = superscripts.get(str(exp), f"^{exp}")
        prefix = f"PI-TCN (λ=10{exp_str})"
    else:
        prefix = f"PI-TCN (λ={lam:.1e})"

    if is_best:
        return f"★ Best {prefix}"
    return prefix


def resolve_csv_path(user_path: str, default_name: str, fallback_dir: str) -> str:
    """Resolve file path with fallback to root or parent directories."""
    candidates = [
        user_path,
        os.path.join(fallback_dir, default_name),
        default_name,
        os.path.join("results", default_name),
        os.path.join("..", fallback_dir, default_name),
        os.path.join("..", default_name),
    ]
    for p in candidates:
        if p and os.path.exists(p):
            return p
    return user_path


def plot_tcn_benchmarks(
    clean_csv: str = "results_clean/benchmark_clean.csv",
    aug_csv: str = "results_augmented/benchmark_augmented.csv",
    out_dir: str = "plots"
):
    os.makedirs(out_dir, exist_ok=True)

    clean_path = resolve_csv_path(clean_csv, "benchmark_clean.csv", "results_clean")
    aug_path = resolve_csv_path(aug_csv, "benchmark_augmented.csv", "results_augmented")

    dfs = []
    if os.path.exists(clean_path):
        print(f"[DataLoader] Found Clean benchmark CSV: {clean_path}")
        df_clean = pd.read_csv(clean_path)
        if "Condition" not in df_clean.columns:
            df_clean["Condition"] = "Clean"
        dfs.append(df_clean)
    else:
        print(f"[DataLoader] Note: Clean benchmark CSV not found at {clean_path}")

    if os.path.exists(aug_path):
        print(f"[DataLoader] Found Augmented benchmark CSV: {aug_path}")
        df_aug = pd.read_csv(aug_path)
        if "Condition" not in df_aug.columns:
            df_aug["Condition"] = "Augmented"
        dfs.append(df_aug)
    else:
        print(f"[DataLoader] Note: Augmented benchmark CSV not found at {aug_path}")

    if not dfs:
        print(f"[Error] No benchmark CSVs could be loaded. Checked paths:\n  - {clean_path}\n  - {aug_path}")
        print("Please run `train_tcn.py` first to generate benchmark results, or specify paths via CLI arguments.")
        return

    df_all = pd.concat(dfs, ignore_index=True)

    # Standardize column naming and compute numeric coverage
    # Dropout_Level can be "10%", "20%", or numeric 10, 20
    if df_all["Dropout_Level"].dtype == object:
        df_all["Dropout_Pct"] = df_all["Dropout_Level"].astype(str).str.replace("%", "").astype(float)
    else:
        df_all["Dropout_Pct"] = df_all["Dropout_Level"].astype(float)
    df_all["PMU_Coverage_Pct"] = 100.0 - df_all["Dropout_Pct"]
    df_all["Lambda"] = df_all["Lambda"].astype(float)

    # Set publication plot style
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    plt.rcParams.update({
        "font.family": "serif",
        "font.size": 10,
        "axes.labelsize": 11,
        "axes.titlesize": 12,
        "xtick.labelsize": 10,
        "ytick.labelsize": 10,
        "legend.fontsize": 8.5,
        "figure.titlesize": 13,
    })

    conditions = df_all["Condition"].unique()

    for cond in conditions:
        sub = df_all[df_all["Condition"] == cond].copy()
        if sub.empty:
            continue

        print(f"\n" + "=" * 70)
        print(f" Processing Condition: {cond} ({len(sub)} evaluation rows)")
        print("=" * 70)

        # Unique lambdas sorted ascending
        lambdas = sorted(sub["Lambda"].unique())
        print(f" Detected λ sweep values ({len(lambdas)}): {lambdas}")

        # Determine Best Physics Regularized Lambda (lowest average validation/composite error)
        # Using composite metric: (RMSE_V / 0.01) + (RMSE_Theta / 0.1)
        sub["Composite_Score"] = (sub["RMSE_V_pu"] / 0.01) + (sub["RMSE_Theta_deg"] / 0.1)
        
        pinn_sub = sub[sub["Lambda"] > 0.0]
        if not pinn_sub.empty:
            mean_scores = pinn_sub.groupby("Lambda")["Composite_Score"].mean()
            best_lam = mean_scores.idxmin()
            print(f" ★ Best Physics-Informed Regularizer: λ = {best_lam} (Composite score: {mean_scores[best_lam]:.4f})")
        else:
            best_lam = None
            print(" [Notice] Only Baseline (λ=0) present in dataset.")

        # Setup 2-Panel Figure
        fig, axes = plt.subplots(1, 2, figsize=(14, 5.5), dpi=300)

        # Color mapping for the non-baseline and non-best lambdas
        pinn_lams = [l for l in lambdas if l > 0 and l != best_lam]
        if pinn_lams:
            log_lams = [math.log10(max(l, 1e-6)) for l in pinn_lams]
            norm = Normalize(vmin=min(log_lams), vmax=max(log_lams))
            cmap = cm.viridis
        else:
            norm = None
            cmap = None

        markers = ["^", "v", "<", ">", "D", "p", "P", "X", "h", "*"]

        # Loop through metrics: (0) Voltage Magnitude, (1) Voltage Phase Angle
        metrics = [
            {
                "col": "RMSE_V_pu",
                "scale": 1000.0,  # Convert to milli-pu (x 10^-3)
                "ylabel": "RMSE |V| (× 10⁻³ pu)",
                "title": f"Voltage Magnitude Error vs. PMU Coverage\n({cond} Training Regime)",
                "ax": axes[0]
            },
            {
                "col": "RMSE_Theta_deg",
                "scale": 1.0,  # Keep in degrees
                "ylabel": "RMSE θ (degrees)",
                "title": f"Voltage Phase Angle Error vs. PMU Coverage\n({cond} Training Regime)",
                "ax": axes[1]
            }
        ]

        for m_info in metrics:
            ax = m_info["ax"]
            col = m_info["col"]
            scale = m_info["scale"]

            marker_idx = 0
            # 1. First plot secondary regularized curves (background)
            for lam in lambdas:
                if lam == 0.0 or lam == best_lam:
                    continue
                group = sub[sub["Lambda"] == lam].sort_values("PMU_Coverage_Pct")
                lbl = format_lambda_label(lam, is_best=False)
                marker = markers[marker_idx % len(markers)]
                marker_idx += 1
                color = cmap(norm(math.log10(lam))) if norm else "#888888"
                ax.plot(
                    group["PMU_Coverage_Pct"],
                    group[col] * scale,
                    linestyle=":",
                    marker=marker,
                    color=color,
                    alpha=0.72,
                    linewidth=1.3,
                    markersize=5,
                    label=lbl,
                    zorder=4
                )

            # 2. Plot Baseline curve (prominently)
            if 0.0 in lambdas:
                base_group = sub[sub["Lambda"] == 0.0].sort_values("PMU_Coverage_Pct")
                ax.plot(
                    base_group["PMU_Coverage_Pct"],
                    base_group[col] * scale,
                    linestyle="--",
                    marker="o",
                    color="#D9534F",  # Crimson / Dark Coral
                    linewidth=2.5,
                    markersize=6.5,
                    label=format_lambda_label(0.0),
                    zorder=8
                )

            # 3. Plot Best PI-TCN curve (forefront highlight)
            if best_lam is not None:
                best_group = sub[sub["Lambda"] == best_lam].sort_values("PMU_Coverage_Pct")
                ax.plot(
                    best_group["PMU_Coverage_Pct"],
                    best_group[col] * scale,
                    linestyle="-",
                    marker="s",
                    color="#0066CC",  # Sharp Deep Cobalt / Azure
                    linewidth=2.7,
                    markersize=7.0,
                    label=format_lambda_label(best_lam, is_best=True),
                    zorder=10
                )

            ax.set_title(m_info["title"], fontweight="bold", pad=12)
            ax.set_xlabel("PMU Measurement Coverage (%)", fontweight="semibold")
            ax.set_ylabel(m_info["ylabel"], fontweight="semibold")
            ax.set_xticks([50, 60, 70, 80, 90])
            ax.xaxis.set_major_formatter(ticker.FormatStrFormatter("%d%%"))
            ax.grid(True, linestyle="--", alpha=0.55, color="#CCCCCC")

            # Place legend with tidy layout
            ax.legend(
                loc="upper right" if col == "RMSE_V_pu" else "upper right",
                frameon=True,
                framealpha=0.92,
                facecolor="white",
                edgecolor="#E0E0E0",
                ncol=2 if len(lambdas) > 5 else 1
            )

        plt.tight_layout()
        plot_path = os.path.join(out_dir, f"tcn_rmse_vs_coverage_{cond.lower()}.png")
        plt.savefig(plot_path, dpi=300, bbox_inches="tight")
        plt.close()
        print(f" [PlotSaved] High-res 300 DPI chart saved to: {plot_path}")

    print("\n" + "=" * 70)
    print(f" All publication plots generated successfully in: {os.path.abspath(out_dir)}/")
    print("=" * 70)


def main():
    parser = argparse.ArgumentParser(
        description="Generate publication-quality RMSE vs. Coverage plots for TCN State Estimator"
    )
    parser.add_argument(
        "--clean_csv",
        type=str,
        default="results_clean/benchmark_clean.csv",
        help="Path to Clean condition benchmark CSV (default: results_clean/benchmark_clean.csv)"
    )
    parser.add_argument(
        "--aug_csv",
        type=str,
        default="results_augmented/benchmark_augmented.csv",
        help="Path to Augmented condition benchmark CSV (default: results_augmented/benchmark_augmented.csv)"
    )
    parser.add_argument(
        "--out_dir",
        type=str,
        default="plots",
        help="Directory to save output PNG plots (default: plots)"
    )
    args = parser.parse_args()

    plot_tcn_benchmarks(
        clean_csv=args.clean_csv,
        aug_csv=args.aug_csv,
        out_dir=args.out_dir
    )


if __name__ == "__main__":
    main()
